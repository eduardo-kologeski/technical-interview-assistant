package com.kologeski.interviewassistant.interviewkit;

import com.kologeski.interviewassistant.audit.*;
import com.kologeski.interviewassistant.company.*;
import com.kologeski.interviewassistant.interview.Interview;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import tools.jackson.databind.ObjectMapper;
import java.time.*;
import java.util.*;
import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.*;

class InterviewKitServiceTest {
    @Test void publishingANewVersionDoesNotChangeTheHistoricalSnapshot() {
        var dataSource = new DriverManagerDataSource("jdbc:h2:mem:kits;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        var sql = new JdbcTemplate(dataSource);
        sql.execute("create table interview_kits(id uuid primary key,company_id uuid,vacancy_id uuid,name varchar(160),created_at timestamp with time zone,created_by varchar(255))");
        sql.execute("create table interview_kit_versions(id uuid primary key,kit_id uuid,version_number int,status varchar(24),published_at timestamp with time zone,created_at timestamp with time zone,created_by varchar(255))");
        sql.execute("create table interview_kit_items(id bigint generated by default as identity primary key,version_id uuid,position int,criterion varchar(160),question varchar(2000),weight int,rubric varchar(5000))");
        UUID company = UUID.randomUUID(), vacancy = UUID.randomUUID();
        var authorization = mock(CompanyAuthorizationPolicy.class);
        when(authorization.require(any())).thenReturn(new CompanyContext.ActiveCompany(company, 42L, CompanyRole.COMPANY_ADMIN));
        var audit = mock(AuditTrailService.class);
        var service = new InterviewKitService(JdbcClient.create(dataSource), authorization,
                () -> new CurrentActor.AuthenticatedActor("42", "Admin"), audit, new ObjectMapper(),
                Clock.fixed(Instant.parse("2026-08-31T12:00:00Z"), ZoneOffset.UTC));
        service.initialize(vacancy, company, "Backend", List.of("Java"), "42");
        String historical = service.publishedSnapshot(vacancy, company);
        var interview = new Interview(company, vacancy, "Backend", "Pleno", List.of("Java"),
                "Candidata", "Cliente", "42", Instant.parse("2026-08-31T12:00:00Z"));
        interview.snapshotKit(historical);
        var draft = service.saveDraft(vacancy, "Backend", List.of(
                new InterviewKitService.ItemInput("Java", "Explique concorrência", 5, "0 sem evidência; 5 domínio")));
        service.publish(vacancy, draft.id());
        String current = service.publishedSnapshot(vacancy, company);

        assertThat(historical).contains("Avalie evidências práticas").doesNotContain("Explique concorrência");
        assertThat(current).contains("Explique concorrência");
        assertThat(historical).isNotEqualTo(current);
        assertThat(interview.kitSnapshot()).isEqualTo(historical).doesNotContain("Explique concorrência");
        verify(audit).record(company, 42L, "DOMAIN", "KIT_PUBLISHED", "INTERVIEW_KIT_VERSION", draft.id());
    }
}
