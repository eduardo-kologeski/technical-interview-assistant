CREATE TABLE interview_kits (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL REFERENCES companies(id),
    vacancy_id UUID NOT NULL REFERENCES job_vacancies(id),
    name VARCHAR(160) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    CONSTRAINT uk_interview_kit_vacancy UNIQUE (vacancy_id)
);

CREATE TABLE interview_kit_versions (
    id UUID PRIMARY KEY,
    kit_id UUID NOT NULL REFERENCES interview_kits(id),
    version_number INTEGER NOT NULL,
    status VARCHAR(24) NOT NULL,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    CONSTRAINT uk_interview_kit_version UNIQUE (kit_id, version_number)
);

CREATE TABLE interview_kit_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id UUID NOT NULL REFERENCES interview_kit_versions(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    criterion VARCHAR(160) NOT NULL,
    question TEXT NOT NULL,
    weight INTEGER NOT NULL CHECK (weight BETWEEN 1 AND 10),
    rubric TEXT NOT NULL,
    CONSTRAINT uk_interview_kit_item_position UNIQUE (version_id, position)
);

