CREATE TABLE IF NOT EXISTS interview_kits (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL,
    vacancy_id UUID NOT NULL,
    name VARCHAR(160) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    CONSTRAINT uk_interview_kit_vacancy UNIQUE (vacancy_id)
);

CREATE TABLE IF NOT EXISTS interview_kit_versions (
    id UUID PRIMARY KEY,
    kit_id UUID NOT NULL,
    version_number INTEGER NOT NULL,
    status VARCHAR(24) NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    CONSTRAINT uk_interview_kit_version UNIQUE (kit_id, version_number)
);

CREATE TABLE IF NOT EXISTS interview_kit_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id UUID NOT NULL,
    position INTEGER NOT NULL,
    criterion VARCHAR(160) NOT NULL,
    question VARCHAR(4000) NOT NULL,
    weight INTEGER NOT NULL CHECK (weight BETWEEN 1 AND 10),
    rubric VARCHAR(4000) NOT NULL,
    CONSTRAINT uk_interview_kit_item_position UNIQUE (version_id, position)
);

CREATE INDEX IF NOT EXISTS idx_interview_kits_company ON interview_kits(company_id);
CREATE INDEX IF NOT EXISTS idx_interview_kit_versions_kit_status ON interview_kit_versions(kit_id, status);
